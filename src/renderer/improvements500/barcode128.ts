const START_B = 104;
const STOP = 106;

/** Compute Code-128 checksum value for subset B over ASCII string. */
export function code128Checksum(text: string): number {
  let sum = START_B;
  for (let i = 0; i < text.length; i += 1) {
    const code = text.charCodeAt(i);
    if (code < 32 || code > 127) throw new Error(`code128: char "${text[i]}" out of subset B range`);
    sum += (code - 32) * (i + 1);
  }
  return sum % 103;
}

/** Encode `text` as a binary bar pattern string ('1' = bar, '0' = space). */
export function code128Encode(text: string): string {
  const checksum = code128Checksum(text);
  let bits = PATTERNS_128[START_B]!;
  for (let i = 0; i < text.length; i += 1) {
    const idx = text.charCodeAt(i) - 32;
    bits += PATTERNS_128[idx]!;
  }
  bits += PATTERNS_128[checksum]!;
  bits += PATTERNS_128[STOP]!;
  return bits;
}
