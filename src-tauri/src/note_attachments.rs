//! Notes attachments on disk: `dexnotes:addAttachment`, `removeAttachment`,
//! `openAttachment`. These used to answer "not ported", so the Notes attach
//! button, drop target and attachment list did nothing.
//!
//! A file is COPIED into `<data>/note-attachments/<noteId>/` (the original is
//! never moved or changed) and recorded in `note_attachments`. Remove deletes the
//! row, and the copy only when it lives inside that folder. Open hands the copy
//! to the Windows default app.

use rusqlite::{params, Connection, OptionalExtension};
use serde_json::{json, Value};
use std::path::{Path, PathBuf};

/// 512 MB per attachment; Notes is not a file store.
const MAX_BYTES: u64 = 512 * 1024 * 1024;

fn fail(msg: impl Into<String>) -> Value {
    json!({ "success": false, "error": msg.into() })
}

fn now_ms() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_millis() as i64)
        .unwrap_or(0)
}

pub fn root(data_dir: &Path) -> PathBuf {
    data_dir.join("note-attachments")
}

/// Folder-safe note id (ids are generated by DEX, but never trust a path piece).
fn safe_segment(s: &str) -> Option<String> {
    let t: String = s.chars().filter(|c| c.is_ascii_alphanumeric() || *c == '-' || *c == '_').collect();
    if t.is_empty() || t.len() > 128 { None } else { Some(t) }
}

fn safe_file_name(name: &str) -> String {
    let base = name.rsplit(['/', '\\']).next().unwrap_or("");
    let mut n: String = base
        .chars()
        .filter(|c| !c.is_control() && !matches!(c, '<' | '>' | ':' | '"' | '|' | '?' | '*'))
        .collect();
    while n.ends_with('.') || n.ends_with(' ') {
        n.pop();
    }
    if n.trim().is_empty() || n == ".." { "file".into() } else { n.chars().take(150).collect() }
}

pub fn kind_of(name: &str) -> &'static str {
    let ext = name.rsplit('.').next().unwrap_or("").to_ascii_lowercase();
    match ext.as_str() {
        "png" | "jpg" | "jpeg" | "gif" | "webp" | "bmp" | "svg" | "avif" | "heic" => "image",
        "mp4" | "mov" | "mkv" | "webm" | "avi" | "m4v" => "video",
        "mp3" | "wav" | "flac" | "ogg" | "m4a" | "aac" | "opus" => "audio",
        "pdf" => "pdf",
        _ => "file",
    }
}

fn note_exists(conn: &Connection, id: &str) -> bool {
    conn.query_row("SELECT 1 FROM notes WHERE id = ?", params![id], |_| Ok(()))
        .optional()
        .ok()
        .flatten()
        .is_some()
}

pub fn add(conn: &Connection, data_dir: &Path, note_id: &str, source: &str) -> Value {
    let Some(seg) = safe_segment(note_id) else { return fail("Unknown note.") };
    if !note_exists(conn, note_id) {
        return fail("That note no longer exists.");
    }
    let src = Path::new(source);
    let meta = match std::fs::metadata(src) {
        Ok(m) if m.is_file() => m,
        Ok(_) => return fail("Pick a file, not a folder."),
        Err(e) => return fail(format!("Can't read the file: {e}")),
    };
    if meta.len() > MAX_BYTES {
        return fail("Attachments can be up to 512 MB.");
    }
    let name = safe_file_name(&src.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default());
    let id = crate::util::pseudo_uuid_v4();
    let dir = root(data_dir).join(&seg);
    if let Err(e) = std::fs::create_dir_all(&dir) {
        return fail(format!("Can't create the attachments folder: {e}"));
    }
    // Prefix with the id so two files with one name never collide.
    let dest = dir.join(format!("{}-{}", &id[..8], name));
    if let Err(e) = std::fs::copy(src, &dest) {
        let _ = std::fs::remove_file(&dest);
        return fail(format!("Couldn't copy the file: {e}"));
    }
    let created = now_ms();
    let kind = kind_of(&name);
    let dest_s = dest.to_string_lossy().into_owned();
    let ins = conn.execute(
        "INSERT INTO note_attachments (id, note_id, file_path, file_name, file_type, file_size, thumbnail_path, created_at)
         VALUES (?, ?, ?, ?, ?, ?, NULL, ?)",
        params![id, note_id, dest_s, name, kind, meta.len() as i64, created],
    );
    if let Err(e) = ins {
        let _ = std::fs::remove_file(&dest);
        return fail(format!("Couldn't save the attachment: {e}"));
    }
    json!({
        "success": true,
        "attachment": {
            "id": id, "note_id": note_id, "file_path": dest_s, "file_name": name,
            "file_type": kind, "file_size": meta.len(), "thumbnail_path": Value::Null, "created_at": created,
        }
    })
}

fn path_of(conn: &Connection, id: &str) -> Option<String> {
    conn.query_row("SELECT file_path FROM note_attachments WHERE id = ?", params![id], |r| r.get::<_, String>(0))
        .optional()
        .ok()
        .flatten()
}

/// True when `p` is inside the attachments folder (so we only ever delete our copies).
fn owned(data_dir: &Path, p: &Path) -> bool {
    match (std::fs::canonicalize(root(data_dir)), std::fs::canonicalize(p)) {
        (Ok(r), Ok(f)) => f.starts_with(r),
        _ => false,
    }
}

pub fn remove(conn: &Connection, data_dir: &Path, id: &str) -> Value {
    let Some(path) = path_of(conn, id) else { return fail("That attachment is already gone.") };
    let p = PathBuf::from(&path);
    if p.exists() && owned(data_dir, &p) {
        if let Err(e) = std::fs::remove_file(&p) {
            return fail(format!("Couldn't delete the file: {e}"));
        }
    }
    match conn.execute("DELETE FROM note_attachments WHERE id = ?", params![id]) {
        Ok(_) => json!({ "success": true }),
        Err(e) => fail(format!("Couldn't remove the attachment: {e}")),
    }
}

/// Resolve the file to open; the caller hands it to the OS.
pub fn open_target(conn: &Connection, id: &str) -> Result<PathBuf, String> {
    let path = path_of(conn, id).ok_or_else(|| "That attachment is gone.".to_string())?;
    let p = PathBuf::from(path);
    if !p.is_file() {
        return Err("The attached file is missing from disk.".into());
    }
    Ok(p)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn setup() -> (Connection, PathBuf) {
        let conn = Connection::open_in_memory().unwrap();
        crate::notes::ensure_schema(&conn);
        conn.execute(
            "INSERT INTO notes (id, title, content, plain_text, created_at, updated_at) VALUES ('n1','T','','',0,0)",
            [],
        )
        .unwrap();
        let dir = std::env::temp_dir().join(format!("dex-att-{}", crate::util::pseudo_uuid_v4()));
        std::fs::create_dir_all(&dir).unwrap();
        (conn, dir)
    }

    #[test]
    fn add_copies_records_and_remove_deletes_only_the_copy() {
        let (conn, dir) = setup();
        let src = dir.join("photo.JPG");
        std::fs::write(&src, b"img").unwrap();
        let r = add(&conn, &dir, "n1", src.to_str().unwrap());
        assert_eq!(r["success"], true, "{r}");
        let a = &r["attachment"];
        assert_eq!(a["file_type"], "image");
        assert_eq!(a["file_size"], 3);
        let copy = PathBuf::from(a["file_path"].as_str().unwrap());
        assert!(copy.starts_with(root(&dir)));
        assert_eq!(std::fs::read(&copy).unwrap(), b"img");
        let id = a["id"].as_str().unwrap();
        assert_eq!(open_target(&conn, id).unwrap(), copy);

        assert_eq!(remove(&conn, &dir, id)["success"], true);
        assert!(!copy.exists(), "copy deleted");
        assert!(src.exists(), "original untouched");
        assert!(open_target(&conn, id).is_err());
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn refuses_bad_input_and_never_deletes_outside_its_folder() {
        let (conn, dir) = setup();
        assert_eq!(add(&conn, &dir, "missing", dir.to_str().unwrap())["success"], false);
        assert_eq!(add(&conn, &dir, "n1", dir.to_str().unwrap())["success"], false, "folder refused");
        assert_eq!(add(&conn, &dir, "../x", "C:/nope")["success"], false);
        // A row pointing at a file outside the attachments folder: row goes, file stays.
        let outside = dir.join("keep.txt");
        std::fs::write(&outside, b"keep").unwrap();
        conn.execute(
            "INSERT INTO note_attachments (id, note_id, file_path, file_name, created_at) VALUES ('a1','n1',?,'keep.txt',0)",
            params![outside.to_string_lossy()],
        )
        .unwrap();
        assert_eq!(remove(&conn, &dir, "a1")["success"], true);
        assert!(outside.exists());
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn names_and_kinds() {
        assert_eq!(safe_file_name("..\\..\\a<b>.pdf"), "ab.pdf");
        assert_eq!(safe_file_name(".."), "file");
        assert_eq!(kind_of("x.mp3"), "audio");
        assert_eq!(kind_of("x.tar.gz"), "file");
    }
}
