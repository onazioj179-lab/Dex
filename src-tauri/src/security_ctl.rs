// =============================================================================
// DEX Tauri — Security subsystem (port of the `security:getPolicy` IPC handler).
//
// NAMING / SOURCE NOTE (documented divergence from the porting brief): the brief
// named the Electron source `src/main/controllers/SecurityController.ts` with
// `electron-store:security` storage. SecurityController.ts is the permission-
// registry / sandbox controller and exposes NO channel named `security:getPolicy`
// (its channels are security:getPermissions / togglePermission / getReport /
// getLog / verifySandbox / exportAudit, plus the Phase 39/40 extended set). The
// real owner of `security:getPolicy` is src/main/security/SecurityContinuumManager.ts
// (System 8 — "Security as a Continuum"), and it does NOT use electron-store: it
// persists with raw fs to JSON files under `<userData>/security/`:
//   - <userData>/security/policy.json : SecurityPolicy (a flat object)
//   - <userData>/security/locks.json  : { version, savedAt, locks[] }
//   - <userData>/security/events.json : { version, savedAt, events[] }
// This is the fs-json storage tier (same precedent as privacy_ctl.rs), so per the
// brief we mirror the SAME relative path under <appData>:
//   <appData>/security/policy.json
//
// CHANNEL MAPPING:
//   - getPolicy -> security:getPolicy : returns `{ ...this.policy }`. On load the
//     manager builds `this.policy = { ...defaultPolicy(), ...JSON.parse(policy.json) }`
//     (defaults alone when the file is absent). We reproduce that read + shallow
//     merge and return the merged SecurityPolicy field-for-field, so the renderer
//     is unchanged. policy.json is a FLAT object (no top-level key wrapper), so we
//     read/write it flat — matching the source exactly.
//   - scan / update / audit -> NOW PORTED natively against SecurityController.ts
//     (the permission-registry / sandbox owner of the `security:` namespace); see
//     the HEAVY-CHANNEL PORT block below. The SecurityContinuumManager live-
//     runtime surface (trust-elevation auth, OS biometric/keychain via
//     safeStorage+systemPreferences, idle/timeout monitors, lock enforcement, the
//     mutating updatePolicy setter, the continuum event log) is distinct and
//     remains unported (updatePolicy / getEvents -> Value::Null).
//
// SecurityPolicy shape (defaultPolicy() in SecurityContinuumManager.ts):
//   { trustTimeouts: { public, basic, standard, elevated, maximum },
//     autoLockOnIntentSwitch, autoLockOnIdle, idleTimeoutMs,
//     requireBiometricForVault, require2FAForExports,
//     maxFailedAttempts, lockoutDurationMs,
//     notifyOnSecurityChange, notifyOnFailedAttempt }
//
// DIVERGENCES (documented):
//   - INFINITY: defaultPolicy() sets trustTimeouts.public = Infinity. Electron
//     persists/returns this over JSON, where `JSON.stringify(Infinity)` yields
//     `null` — so the value the renderer actually receives for public is null.
//     serde_json likewise cannot represent a non-finite number, so we emit
//     Value::Null for `public`, which is byte-identical to what crosses the
//     Electron IPC boundary. (Any finite override present in policy.json is
//     preserved by the merge.)
//   - Read-only: a stateless read dispatch does not reproduce loadData()'s
//     fresh-context reset or saveData()'s first-run write; it only READS. An
//     absent/corrupt policy.json yields the same default policy the renderer
//     would otherwise receive.
//   - Merge semantics mirror `{ ...defaultPolicy(), ...JSON.parse(file) }`:
//     top-level keys present in the file override defaults; missing keys fall back
//     to defaults. No deep merge (matches the spread), so a partial trustTimeouts
//     object in the file replaces the default whole, exactly as in Electron.
//   - No ids or timestamps are generated by the ported channel, so
//     crate::util::pseudo_uuid_v4 / SystemTime are unused here (id/timestamp
//     generation lives only in the skipped heavy channels).
//
// HEAVY-CHANNEL PORT (scan / update / audit) — these were previously skipped and
// returned Value::Null. They are now implemented natively against the OTHER
// owner of the `security:` namespace, SecurityController.ts (the permission-
// registry / sandbox controller), whose `scan`/`update`/`audit` surface is pure
// computation over a static permission registry plus an fs-json audit export —
// all reproducible without an LLM/JS runtime:
//
//   scan  -> security:getReport / security:perform-deep-check :
//            generateSecurityReport() — appVersion + reportDate + permissions +
//            verifySandbox() + risks + recommendations. We also accept the
//            verifySandbox()-only and getPermissions()-only shapes via sub-args.
//   update-> security:togglePermission(id, enabled) : mutate the (now persisted)
//            permission registry, append a security-log event, return
//            { success, error? }. Required permissions cannot be disabled
//            (matches togglePermission()).
//   audit -> security:exportAudit() : generateSecurityReport() + securityLog +
//            exportedAt, written to <appData>/security-audit.json (Electron wrote
//            <userData>/security-audit.json), return { success, path? }.
//
// PERSISTENCE NOTE: Electron's SecurityController held the registry + log in
// memory (process lifetime). A stateless dispatch has no such process, so to
// make update() durable and observable by a later scan()/audit() we persist the
// registry to <appData>/security/permissions.json and the rolling log (last 100,
// matching logSecurityEvent's cap) to <appData>/security/audit-log.json. The
// returned SHAPES are byte-identical to the Electron handlers; only the lifetime
// changes (file-backed instead of memory-backed), which is the documented
// fs-json storage tier already used by getPolicy above.
// =============================================================================

