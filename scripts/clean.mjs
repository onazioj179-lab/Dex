// Safe cleanup of regenerable build/test output in THIS repository.
//
//   node scripts/clean.mjs                 preview (dry run): what would go, and why
//   node scripts/clean.mjs --confirm       delete exactly the previewed items
//   node scripts/clean.mjs --rust          also include src-tauri/target/debug
//                                          (rebuilding it takes a long time)
//
// Rules, checked for every candidate before it is even listed:
//   - inside the repository, never a symlink out of it;
//   - ignored by git (`git check-ignore`) and containing no tracked file;
//   - on the regenerable list below (build outputs, caches, test reports);
//   - never: release builds and installers (src-tauri/target/release, bundles:
//     rollback assets), node_modules itself, .git, user data (DEX's profile
//     lives under %APPDATA%, which this script never looks at).
// Deletion errors (a locked file, a running dev server) are reported per item
// and the script exits non-zero; nothing else is touched.

import { execFileSync } from 'node:child_process';
import { lstatSync, readdirSync, rmSync, statSync, realpathSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = new Set(process.argv.slice(2));
const confirm = args.has('--confirm');

/** Regenerable outputs, with who makes them. */
export const CANDIDATES = [
  { rel: 'dist', why: 'renderer build output (npm run build:renderer)' },
  { rel: 'test-results', why: 'Playwright test output' },
  { rel: 'playwright-report', why: 'Playwright HTML report' },
  { rel: 'coverage', why: 'unit-test coverage report' },
  { rel: 'node_modules/.vite', why: 'Vite dependency pre-bundle cache (rebuilt on next dev start)' },
  { rel: 'node_modules/.cache', why: 'tool caches (eslint/babel), regenerated on demand' },
  { rel: 'src-tauri/gen', why: 'Tauri generated schemas (regenerated by tauri build/dev)', optional: true },
  { rel: 'src-tauri/target/debug', why: 'Rust debug build (cargo rebuilds it; slow)', rust: true },
];

/** Never deleted, whatever else says. */
export const PROTECTED = ['.git', 'node_modules', 'src', 'src-tauri/src', 'src-tauri/target/release', 'core', 'docs', 'tests', 'scripts', 'assets', 'store'];

const git = (...a) => { try { return execFileSync('git', a, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); } catch { return null; } };

function sizeOf(p, budget = { files: 200_000 }) {
  let total = 0;
  const stack = [p];
  while (stack.length && budget.files > 0) {
    const cur = stack.pop();
    let st; try { st = lstatSync(cur); } catch { continue; }
    if (st.isSymbolicLink()) continue;
    if (st.isDirectory()) { try { for (const e of readdirSync(cur)) stack.push(path.join(cur, e)); } catch { /* unreadable */ } }
    else { total += st.size; budget.files--; }
  }
  return { bytes: total, partial: budget.files <= 0 };
}

const mb = (b) => `${(b / 1048576).toFixed(1)} MB`;

export function checkCandidate(rel) {
  const abs = path.resolve(root, rel);
  if (!abs.startsWith(root + path.sep)) return 'outside the repository';
  if (PROTECTED.some((p) => rel === p || p.startsWith(rel + '/'))) return 'protected path';
  let st;
  try { st = lstatSync(abs); } catch { return 'not present'; }
  if (st.isSymbolicLink()) return 'is a link (not followed)';
  try { if (!realpathSync(abs).startsWith(root)) return 'resolves outside the repository'; } catch { return 'cannot resolve'; }
  if (git('check-ignore', '-q', rel) === null) return 'not ignored by git';
  const tracked = git('ls-files', '--', rel);
  if (tracked) return 'contains tracked files';
  return null;
}

function main() {
  const rows = [];
  for (const c of CANDIDATES) {
    if (c.rust && !args.has('--rust')) { rows.push({ ...c, skip: 'Rust build output (use --rust)' }); continue; }
    const why = checkCandidate(c.rel);
    if (why) { rows.push({ ...c, skip: why }); continue; }
    const { bytes, partial } = sizeOf(path.resolve(root, c.rel));
    rows.push({ ...c, bytes, partial });
  }
  const go = rows.filter((r) => !r.skip);
  console.log(confirm ? 'DEX cleanup (deleting):' : 'DEX cleanup preview (nothing is deleted; add --confirm):');
  for (const r of go) console.log(`  remove  ${r.rel.padEnd(26)} ${(r.partial ? '>' : '') + mb(r.bytes)}  — ${r.why}`);
  for (const r of rows.filter((x) => x.skip && x.skip !== 'not present')) console.log(`  keep    ${r.rel.padEnd(26)} ${r.skip}`);
  const total = go.reduce((n, r) => n + r.bytes, 0);
  console.log(`  ${go.length} item(s), about ${mb(total)}.`);
  if (!confirm) return 0;
  let failed = 0;
  for (const r of go) {
    try { rmSync(path.resolve(root, r.rel), { recursive: true, force: false, maxRetries: 2 }); console.log(`  deleted ${r.rel}`); }
    catch (e) { failed++; console.error(`  FAILED  ${r.rel}: ${e.code || e.message} (in use? stop the dev server and retry)`); }
  }
  return failed ? 1 : 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exit(main());
